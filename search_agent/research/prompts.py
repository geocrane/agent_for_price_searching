def verify_user(need: str, period: str | None, url: str, title: str, excerpt: str,
                links: list[str] | None = None) -> str:
    """Сообщение пользователя для проверки источника (что ищем + что видно на странице)."""
    parts = ["=== ЧТО ИЩЕМ ===", need or "данные"]
    if period:
        parts += ["Требуемый период: %s" % period]
    parts += ["", "=== ИСТОЧНИК ===", "URL: %s" % url]
    if title:
        parts.append("Заголовок: %s" % title)
    if links:
        parts += ["Разделы источника, похожие на вход к данным:"] + ["  - %s" % l for l in links[:5]]
    parts += ["", "=== ТЕКСТ СТРАНИЦЫ (фрагменты) ===", excerpt or "(пусто)"]
    return "\n".join(parts)


def fix_citations_message(problems: dict, known_ids: list[str]) -> str:
    """Текст корректирующей итерации по результату validate_citations."""
    lines = []
    if problems.get("unknown"):
        lines.append("— ссылки на несуществующие источники: %s" % ", ".join(problems["unknown"]))
    for claim in (problems.get("uncited") or [])[:6]:
        lines.append("— без ссылки: «%s»" % claim)
    return FIX_CITATIONS % ("\n".join(lines), ", ".join("[%s]" % s for s in known_ids) or "(нет)")
