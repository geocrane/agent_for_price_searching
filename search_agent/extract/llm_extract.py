def _item_block(item) -> str:
    parts = ["Наименование: %s" % item.name]
    if getattr(item, "part_number", None):
        parts.append("Парт-номер/артикул: %s" % item.part_number)
    raw = getattr(item, "raw", None) or {}
    extras = {k: v for k, v in raw.items()
              if v not in (None, "") and str(k).lower() not in ("наименование", "name", "товар")}
    if extras:
        parts.append("Доп. поля: %s" % "; ".join("%s=%s" % (k, v) for k, v in list(extras.items())[:8]))
    return "\n".join(parts)


def _pn_variants(part_number) -> list[str]:
    """Варианты написания артикула для поиска в тексте: как есть и первый значимый токен.

    В спецификациях артикул часто идёт с довеском — «02355MLH (CR8P04BASAD7)». На сайте
    встречается обычно основная часть, поэтому ищем и её тоже.
    """
    pn = str(part_number or "").strip()
    if not pn:
        return []
    out = [pn]
    head = re.split(r"[\s(/,;]+", pn)[0]
    if len(head) >= 4 and head.lower() != pn.lower():
        out.append(head)
    return out


def _anchor_block(markdown: str, part_number) -> str:
    """Фрагмент страницы вокруг ДОСЛОВНОГО совпадения артикула искомого (или пустая строка).

    Совпавший артикул — самый сильный из возможных сигналов «это тот самый предмет». Показываем
    модели это место отдельно, чтобы она не могла молча его не заметить среди прочего текста.
    """
    md = markdown or ""
    low = md.lower()
    for variant in _pn_variants(part_number):
        pos = low.find(variant.lower())
        if pos < 0:
            continue
        start = md.rfind("\n", 0, max(0, pos - 400)) + 1
        end = md.find("\n", pos + 400)
        fragment = md[start:end if end > 0 else len(md)].strip()
        return (
            "=== АРТИКУЛ ИСКОМОГО НАЙДЕН НА СТРАНИЦЕ ===\n"
            "Артикул «%s» встречается здесь дословно — это тот самый предмет:\n%s\n"
            "Верни его цену. Если рядом с ним цены нет, скажи об этом прямо в note; "
            "молча пропустить это место нельзя.\n" % (variant, fragment)
        )
    return ""


def _hints_block(hints: list[dict]) -> str:
    if not hints:
        return "Структурные ценовые метки со страницы: не обнаружены."
    lines = ["Структурные ценовые метки со страницы (schema.org/microdata/meta) — сверь и уточни:"]
    for h in hints[:20]:
        lines.append("  • %s %s%s [%s]" % (
            h["value"], h["currency"],
            "" if h.get("in_stock") is None else (", в наличии" if h["in_stock"] else ", нет в наличии"),
            h.get("source", "")))
    return "\n".join(lines)


def build_messages(item, url: str, domain: str, markdown: str, hints: list[dict],
                   max_chars: int, include_hints: bool = True, *, focus: bool = True,
                   focus_before: int = 5, focus_after: int = 2) -> list[dict]:
    """Собрать messages для модели (system + user).

    focus=True — умный отбор ценовых блоков (extract/focus.py): короче вход (быстрее), без потери
    цен. focus=False — прежняя тупая обрезка markdown[:max_chars].
    """
    if focus:
        from .focus import focus_pricing
        md = focus_pricing(markdown, item, max_chars, before=focus_before, after=focus_after)
    else:
        md = (markdown or "")[:max_chars]
    # Якорь ищем в ПОЛНОМ markdown: артикул мог остаться за пределами отобранных ценовых блоков.
    anchor = _anchor_block(markdown, getattr(item, "part_number", None))
    user = (
        "=== ИСКОМЫЙ ТОВАР ===\n%s\n\n"
        "=== ИСТОЧНИК ===\nдомен: %s\nURL: %s\n\n"
        "%s%s\n\n"
        "=== СОДЕРЖИМОЕ СТРАНИЦЫ (Markdown) ===\n%s"
    ) % (_item_block(item), domain, url, anchor,
         _hints_block(hints) if include_hints else "", md)
    return [{"role": "system", "content": _SYSTEM}, {"role": "user", "content": user}]


