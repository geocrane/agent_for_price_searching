def build_retry_messages(item, url: str, domain: str, snippet: str) -> list[dict]:
    """Короткий повторный запрос по самым релевантным ценовым блокам.

    Применяется, когда модель вернула пусто, а детерминированная проверка показала, что цена
    искомого на странице, судя по тексту, всё-таки есть (см. focus.looks_answerable).
    """
    user = ("=== ИСКОМЫЙ ТОВАР ===\n%s\n\n=== ИСТОЧНИК ===\n%s (%s)\n\n"
            "=== ФРАГМЕНТ СТРАНИЦЫ ===\n%s") % (_item_block(item), domain, url, snippet)
    return [{"role": "system", "content": _RETRY_SYSTEM}, {"role": "user", "content": user}]


_ALLOWED_MATCH = {"точное", "аналог"}


def parse_response(raw: str, *, max_note: int = 1200, max_found: int = 300,
                   finish: str | None = None) -> tuple[list[dict], list[dict], str, dict]:
    """Разобрать ответ модели.

    Возвращает (цены, «цена по запросу», пояснение, диагностика). Пояснение — общий комментарий
    модели о странице (модель обязана его дать, когда подходящего предмета нет), чтобы «цены нет»
    никогда не выглядело как молчание. Устойчиво к мусору/заборам и к обеим формам ответа: массив
    записей или объект {"prices": [...], "note": "…"}.

    Диагностика — {raw_chars, parsed, dropped, fail} — нужна вызывающему, чтобы отличить
    ТЕХНИЧЕСКИЙ сбой (пустое тело ответа, неразбираемый JSON) от честного «на странице этого нет»
    и от «модель назвала позиции, но ни одна не подошла». Без неё все три случая выглядят
    одинаково — «пустой ответ», и пользователь получает запутывающую причину вместо настоящей.
    """
    diag = {"raw_chars": len(raw or ""), "parsed": False, "dropped": 0, "fail": None,
            "finish": finish}
    if not (raw or "").strip():
        log.warning("Модель вернула пустое тело ответа (0 симв., finish=%s)", finish)
        diag["fail"] = "empty_content"
        return [], [], "", diag
    data = extract_json(raw)
    if data is None:
        # Обрыв по лимиту токенов даёт ровно такой же неразбираемый хвост, но чинится иначе
        # (короче вход или больше лимит), поэтому называем его отдельно.
        diag["fail"] = "truncated" if finish == "length" else "bad_json"
        log.warning("Не удалось разобрать JSON из ответа модели (%d симв., finish=%s)",
                    len(raw or ""), finish)
        return [], [], "", diag
    diag["parsed"] = True
    note = ""
    if isinstance(data, dict):
        # модель могла обернуть в {"prices":[...]} (тогда рядом бывает общий комментарий)
        for key in ("prices", "items", "result", "data"):
            if isinstance(data.get(key), list):
                note = str(data.get("note") or data.get("comment") or "")[:max_note]
                data = data[key]
                break
        else:
            data = [data]
    if not isinstance(data, list):
        return [], [], note, diag
    prices, on_request = [], []
    for el in data:
        if not isinstance(el, dict):
            continue
        match = str(el.get("match", "точное")).strip().lower()
        if match not in _ALLOWED_MATCH:                # "не то"/мусор — пропускаем
            diag["dropped"] += 1
            continue
        common = {
            "match": match,
            "confidence": _clip01(el.get("confidence")),
            "found": str(el.get("found") or "")[:max_found],
            "note": str(el.get("note") or "")[:max_note],
        }
        # «цена по запросу»: предмет найден, но цифры на странице нет — это НЕ «не найдено»
        if el.get("price_on_request") is True:
            on_request.append({"currency": (el.get("currency") or "RUB").upper(), **common})
            continue
        try:
            value = float(el.get("value"))
        except (TypeError, ValueError):
            diag["dropped"] += 1
            continue
        if value <= 0:
            diag["dropped"] += 1
            continue
        prices.append({
            "value": value,
            "currency": (el.get("currency") or "RUB").upper(),
            "unit": str(el.get("unit") or "").strip()[:24],
            "is_offer": el.get("is_offer") if isinstance(el.get("is_offer"), bool) else None,
            "vat": el.get("vat") if isinstance(el.get("vat"), bool) else None,
            "in_stock": el.get("in_stock") if isinstance(el.get("in_stock"), bool) else None,
            **common,
        })
    if not prices and not on_request and not note:     # ответ пуст и без объяснений
        log.info("Модель вернула пустой список без пояснения (отброшено записей: %d)",
                 diag["dropped"])
    return prices, on_request, note, diag


def _clip01(v) -> float | None:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return max(0.0, min(1.0, f))


async def extract_with_model(item, url, domain, markdown, hints, llm_client,
                             model=None, max_chars=20000, include_hints=True,
                             on_chunk=None, *, focus=True, focus_before=5, focus_after=2,
                             max_note=1200) -> tuple[list[dict], list[dict], str, dict | None, dict]:
    """Вызвать модель и вернуть (цены, «по запросу», пояснение, usage, диагностика).

    on_chunk(delta) — для стрима «мышления» в UI. Ошибки транспорта пробрасываются вверх.
    Диагностика (см. parse_response) отличает технический сбой от честного «ничего не нашёл».
    """
    messages = build_messages(item, url, domain, markdown, hints, max_chars, include_hints,
                              focus=focus, focus_before=focus_before, focus_after=focus_after)
    sent = len(messages[1]["content"])
    log.info("Извлечение цены моделью: %s (вход≈%d симв., фокус=%s, подсказок=%d)",
             domain, sent, "да" if focus else "нет", len(hints))
    res = await llm_client.complete(messages, model=model, on_chunk=on_chunk)
    raw = res.get("content", "")
    prices, on_request, note, diag = parse_response(raw, max_note=max_note,
                                                    finish=res.get("finish"))
    log.info("Модель вернула: цен=%d, по запросу=%d%s (%s)%s", len(prices), len(on_request),
             ", есть пояснение" if note else "", domain,
             "" if not diag["fail"] else " — СБОЙ: %s" % diag["fail"])
    return prices, on_request, note, res.get("usage"), diag


async def retry_with_model(item, url, domain, snippet, llm_client, model=None, max_note=1200):
    """Повторный короткий запрос по фрагменту.

    Возвращает (цены, «по запросу», пояснение, usage, диагностика).
    """
    messages = build_retry_messages(item, url, domain, snippet)
    log.info("Повторное извлечение по фрагменту: %s (вход≈%d симв.)", domain, len(snippet))
    res = await llm_client.complete(messages, model=model)
    prices, on_request, note, diag = parse_response(res.get("content", ""), max_note=max_note)
    log.info("Повтор вернул: цен=%d, по запросу=%d (%s)%s", len(prices), len(on_request), domain,
             "" if not diag["fail"] else " — СБОЙ: %s" % diag["fail"])
    return prices, on_request, note, res.get("usage"), diag
